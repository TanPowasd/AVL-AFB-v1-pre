"""Export the clean contestant workspace for rift_era (裂陆纪元) and write manifest hashes.

What goes in (public):
  README.md, GUIDE.md, COMMANDS.md            kit/ sources (COMMANDS.md is generated by pipeline/command_surface.py)
  sdk.py                                      organizer/rift_era/sdk.py, byte-identical
  rules/*.md, rules/data/*.json               organizer/rift_era/designs 00–07, 10, 11 and the frozen rule data
  agents/template/                            kit/template + sdk.py
  agents/medium/, agents/advanced/            public practice bots (decisions/0011), copied verbatim
  runtime/pkg/rift_era/, runtime/designs/...  the engine exactly as the judge runs it (same engine_hash)
  scripts/local_match.py, make_submission.py  local practice match/score and zip builder

What never goes in: Super (scoring pool), config/scoring_v2.json, pipeline/, tests/,
validation/, results/, handoff/implementation notes, prototype/ and decisions/.

    RIFT_ERA_BOTS_ROOT=/path/to/bots python3 organizer/rift_era/scripts/pack_contestant.py --force
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import sys
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]           # organizer/rift_era
REPO = ROOT.parents[1]
DESIGNS = (ROOT / 'designs') if (ROOT / 'designs').is_dir() else (REPO / 'designs' / 'rift_era')
DEFAULT_DESTINATION = REPO / 'contestant' / 'rift_era'
EMPTY_DIRS = ('results', 'replays', 'logs', 'agents/submissions')
RULE_DOCS = ('00_design_principles.md', '01_world_and_realtime.md', '02_economy_logistics_governance.md',
             '03_warfare_diplomacy_intelligence.md', '04_technology_tree.md', '05_industry_system.md',
             '06_agent_interface.md', '07_scoring_and_resources.md', '10_system_coupling.md',
             '11_execution_contract.md')
PUBLIC_TIERS = ('medium', 'advanced')
PRIVATE_MARKERS = ('scoring_v2', 'shadow_cache', 'RIFT_ERA_BOTS_ROOT', 'bots/super',
                   'bots/hegemon', 'bots/arbiter', 'bots/verdant',
                   'rift-hegemon-', 'rift-arbiter-', 'rift-verdant-')
DOC_PRIVATE_WORDS = ('hegemon', 'arbiter', 'verdant')


def private_bot_names(bots: Path) -> tuple[str, ...]:
    names = {'super', 'hegemon', 'arbiter', 'verdant'}
    if bots.is_dir():
        for entry in bots.iterdir():
            if entry.name.startswith('_') or entry.name.startswith('.') or entry.name in PUBLIC_TIERS:
                continue
            if (entry.is_dir() and (entry / 'main.py').is_file()) or (entry.is_file() and entry.suffix == '.zip'):
                names.add(entry.stem if entry.is_file() else entry.name)
    return tuple(sorted(names))


def bots_root() -> Path:
    env = os.environ.get('RIFT_ERA_BOTS_ROOT')
    return Path(env).resolve() if env else ROOT / 'bots'


def public_map(bots: Path) -> list[tuple[Path, str]]:
    items = [(ROOT / 'kit' / 'README.md', 'README.md'), (ROOT / 'kit' / 'GUIDE.md', 'GUIDE.md'),
             (ROOT / 'kit' / 'AGENTS.md', 'AGENTS.md'), (ROOT / 'kit' / 'AI_README.md', 'AI_README.md'),
             (ROOT / 'kit' / 'COMMANDS.md', 'COMMANDS.md'),
             (ROOT / 'kit' / 'handbook' / 'contest-rules.md', 'FORMAT.md'),
             (ROOT / 'kit' / 'handbook' / 'contest-rules.md', 'handbook/contest-rules.md'),
             (ROOT / 'kit' / 'handbook' / 'player-guide.md', 'handbook/player-guide.md'),
             (ROOT / 'kit' / 'handbook' / 'game-facts.md', 'handbook/game-facts.md'),
             (ROOT / 'kit' / 'prompts' / 'task.txt', 'prompts/task.txt'),
             (ROOT / 'sdk.py', 'sdk.py'),
             (ROOT / 'kit' / 'template' / 'main.py', 'agents/template/main.py'),
             (ROOT / 'kit' / 'template' / 'bot.py', 'agents/template/bot.py'),
             (ROOT / 'sdk.py', 'agents/template/sdk.py'),
             (ROOT / 'kit' / 'PUBLIC_BOTS.md', 'agents/PUBLIC_BOTS.md'),
             (ROOT / 'kit' / 'scripts' / 'spar.py', 'scripts/spar.py'),
             (ROOT / 'kit' / 'scripts' / 'local_match.py', 'scripts/local_match.py'),
             (ROOT / 'kit' / 'replay_viz.py', 'scripts/replay_viz.py'),
             (ROOT / 'kit' / 'scripts' / 'record_replay.py', 'scripts/record_replay.py'),
             (ROOT / 'kit' / 'scripts' / 'make_submission.py', 'scripts/make_submission.py'),
             (ROOT / 'viz' / 'player.html', 'viz/player.html')]
    items += [(DESIGNS / name, f'rules/{name}') for name in RULE_DOCS]
    for data in sorted((DESIGNS / 'data').glob('*.json'), key=lambda p: p.name):
        items.append((data, f'rules/data/{data.name}'))
        items.append((data, f'runtime/designs/rift_era/data/{data.name}'))
    items.append((DESIGNS / 'data' / 'README.md', 'rules/data/README.md'))
    pkg = 'runtime/pkg/rift_era'
    for name in ('__init__.py', '__main__.py', 'sdk.py'):
        items.append((ROOT / name, f'{pkg}/{name}'))
    for path in sorted((ROOT / 'engine').glob('*.py'), key=lambda p: p.name):
        items.append((path, f'{pkg}/engine/{path.name}'))
    for path in sorted((ROOT / 'data').glob('*.json'), key=lambda p: p.name):
        items.append((path, f'{pkg}/data/{path.name}'))
    for tier in PUBLIC_TIERS:
        for name in ('main.py', 'bot.py', 'sdk.py'):
            items.append((bots / tier / name, f'agents/{tier}/{name}'))
    return items


def check_sources(items) -> None:
    missing = [str(src) for src, _ in items if not src.is_file()]
    if missing:
        raise ValueError('missing public sources (tier bots need RIFT_ERA_BOTS_ROOT or organizer/rift_era/bots): '
                         + ', '.join(missing))
    sdk = (ROOT / 'sdk.py').read_bytes()
    for src, dst in items:
        if dst.startswith('agents/') and dst.endswith('/sdk.py') and src.read_bytes() != sdk:
            raise ValueError(f'{src} is not a byte-identical copy of organizer/rift_era/sdk.py')


def export_kit(destination: Path = DEFAULT_DESTINATION, *, make_zip: bool = False, force: bool = False,
               bots: Path | None = None) -> Path:
    destination = Path(destination).resolve()
    if destination.is_relative_to(ROOT):
        raise ValueError('contestant folder must be outside organizer/rift_era')
    items = public_map(bots or bots_root())
    check_sources(items)
    archive = destination.with_name(destination.name + '.zip')
    if destination.exists():
        if not force:
            raise ValueError(f'output exists; pass --force: {destination}')
        shutil.rmtree(destination)
    if make_zip and archive.exists():
        if not force:
            raise ValueError(f'archive exists: {archive}')
        archive.unlink()
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.rift-kit-', dir=destination.parent) as tmp:
        staging = Path(tmp) / 'kit'
        for src, dst in items:
            target = staging / dst
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, target)
        (staging / 'config').mkdir()
        (staging / 'config' / 'workspace.json').write_text(
            json.dumps({'format': 'afb-contestant-workspace/1', 'mode': 'contestant', 'problem': 'rift_era'},
                       indent=2) + '\n', encoding='utf-8', newline='\n')
        for d in EMPTY_DIRS:
            (staging / d).mkdir(parents=True, exist_ok=True)
            (staging / d / '.gitkeep').write_text('', encoding='utf-8')
        private_names = private_bot_names(bots or bots_root())
        markers = tuple(dict.fromkeys(list(PRIVATE_MARKERS) + [f'bots/{n}' for n in private_names]))
        leaks = []
        for p in staging.rglob('*'):
            if not p.is_file() or p.suffix not in ('.py', '.md', '.json', '.txt', '.html'):
                continue
            rel_parts = p.relative_to(staging).parts
            if rel_parts[0] == 'rules':
                continue
            text = p.read_text(encoding='utf-8', errors='replace')
            if any(m in text for m in markers):
                leaks.append(p.relative_to(staging).as_posix())
            elif rel_parts[0] != 'runtime' and any(w in text.lower() for w in DOC_PRIVATE_WORDS):
                leaks.append(p.relative_to(staging).as_posix())
        leaked_dirs = [n for n in private_names if (staging / 'agents' / n).exists() or (staging / 'agents' / f'{n}.zip').exists()]
        if leaks or leaked_dirs:
            raise ValueError(f'private organizer material in kit: files={leaks} bots={leaked_dirs}')
        sys.path.insert(0, str(REPO))
        from organizer.rift_era.engine import ENGINE_VERSION
        from organizer.rift_era.engine.determinism import engine_source_fingerprint
        hashes = {p.relative_to(staging).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                  for p in sorted(staging.rglob('*'), key=lambda p: p.relative_to(staging).parts) if p.is_file()}
        manifest = {'format': 'afb-contestant-kit/2', 'problem': 'rift_era',
                    'submission': 'agents/submissions/my_bot.zip（根目录 main.py）',
                    'unified_submission': '../submissions/rift_era.zip',
                    'engine_version': ENGINE_VERSION, 'engine_hash': engine_source_fingerprint(),
                    'public_bots': list(PUBLIC_TIERS), 'files': hashes}
        (staging / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n',
                                               encoding='utf-8', newline='\n')
        if make_zip:
            with zipfile.ZipFile(Path(tmp) / 'kit.zip', 'w', zipfile.ZIP_DEFLATED) as zf:
                for p in sorted(staging.rglob('*'), key=lambda p: p.relative_to(staging).parts):
                    if p.is_file():
                        zf.write(p, p.relative_to(staging).as_posix())
        shutil.move(str(staging), str(destination))
        if make_zip:
            shutil.move(str(Path(tmp) / 'kit.zip'), str(archive))
    return destination


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--out', type=Path, default=DEFAULT_DESTINATION)
    parser.add_argument('--zip', action='store_true')
    parser.add_argument('--force', action='store_true')
    args = parser.parse_args()
    try:
        dest = export_kit(args.out, make_zip=args.zip, force=args.force)
    except (ValueError, OSError) as exc:
        parser.error(str(exc))
    print('Contestant folder:', dest)
    print('Submission: 目录含 main.py → python3 scripts/make_submission.py <dir> --out ../submissions/rift_era.zip')


if __name__ == '__main__':
    main()
