class RecordingPortfolio(AdaptivePortfolio):
    def __init__(self, *args, **kwargs):
        self.column_pool = {}
        super().__init__(*args, **kwargs)
        for pos, project in self.projects.items():
            self.column_pool.setdefault(pos, {})[project.days] = project

    def offer(self, pos, project):
        self.column_pool.setdefault(pos, {})[project.days] = project
        return super().offer(pos, project)


def clone_model(model):
    other = copy.copy(model)
    other.projects = dict(model.projects)
    other.parts = dict(model.parts)
    other.flow = {k: v[:] for k, v in model.flow.items()}
    other.work = model.work[:]
    other.book = copy.copy(model.book)
    # Give every method exactly the same warm baseline cache.
    other.book._parts = dict(model.book._parts)
    other.book._marginals = dict(model.book._marginals)
    return other


def today_cost(project, day):
    total = 0
    for item, count in project.first(day)[3]:
        if item.startswith('SEED_'):
            total += rules.CROPS[item[5:]]['seed'] * count
        elif item in rules.ANIMALS:
            total += rules.ANIMALS[item]['cost'] * count
    return total


def search(model, options, evaluations=600, temperature=0, seed=7,
           finalists=1, candidates_out=None, deadline=None):
    """Same proposed move distribution, budget, start, and objective for all T."""
    start = time.perf_counter()
    rng = random.Random(seed)
    trial = clone_model(model)
    positions = [pos for pos, opts in options.items() if len(opts) > 1]
    indices = {pos: 0 for pos in options}
    baseline = trial.objective()
    current = best = baseline
    best_indices = indices.copy()
    accepted = downhills = best_step = hard_rejections = 0
    columns = {pos: [resources(p, pos) for p in opts] for pos, opts in options.items()}
    costs = {pos: [today_cost(p, model.day) for p in opts] for pos, opts in options.items()}
    initial_today = sum(v[0] for v in costs.values())
    current_today = initial_today
    # A conservative cap does not permit any higher same-day capital commitment.
    cash_cap = initial_today + 1e-6
    changes = []
    finalist_limit=max(1,int(finalists))
    # Store index vectors, not mutable trial models. Tracking consumes no RNG
    # draws and adds no objective evaluations inside the original search loop.
    frontier={}
    if not positions:
        return trial, dict(baseline=baseline, best=best, gain=0, seconds=0, evaluations=0,
                          temperature=temperature, search_seed=seed, accepted=0,
                          downhills=0, hard_rejections=0, best_step=0,
                          capital_before=initial_today,capital_after=initial_today,changes=[])
    performed=0
    for step in range(evaluations):
        if deadline is not None and time.perf_counter()>=deadline:break
        performed+=1
        count = min(len(positions), rng.choices([1, 2, 3, 5], [50, 30, 15, 5])[0])
        chosen = rng.sample(positions, count)
        proposals = []
        proposed_today = current_today
        for pos in chosen:
            old = indices[pos]
            new = rng.randrange(len(options[pos]) - 1)
            if new >= old:
                new += 1
            proposals.append((pos, old, new))
            proposed_today += costs[pos][new] - costs[pos][old]
        if proposed_today > cash_cap:
            hard_rejections += 1
            continue
        for pos, old, new in proposals:
            trial.delta(columns[pos][old], -1)
            trial.delta(columns[pos][new], 1)
        value = trial.objective()
        delta = value - current
        temp = temperature * (0.005 ** (step / max(1, evaluations - 1)))
        # Consume the same random draw under T=0 to keep proposal RNG matched.
        draw = rng.random()
        take = delta > 1e-8 or (temp > 1e-8 and draw < math.exp(min(0, delta / temp)))
        if take:
            accepted += 1
            downhills += delta < -1e-8
            for pos, old, new in proposals:
                indices[pos] = new
            current_today = proposed_today
            current = value
            if value > best + 1e-8:
                best = value
                best_indices = indices.copy()
                best_step = step + 1
            if finalist_limit>1 and value>baseline+1e-8:
                signature=tuple(indices.values())
                if signature not in frontier:
                    if len(frontier)<finalist_limit:
                        frontier[signature]=(value,indices.copy())
                    else:
                        worst=min(frontier,key=lambda key:frontier[key][0])
                        if value>frontier[worst][0]+1e-8:
                            del frontier[worst]
                            frontier[signature]=(value,indices.copy())
        else:
            for pos, old, new in proposals:
                trial.delta(columns[pos][new], -1)
                trial.delta(columns[pos][old], 1)
    # Return the best model incumbent, never the last annealing state.
    # Physical certification is separate and may reject this incumbent.
    result = clone_model(model)
    for pos, index in best_indices.items():
        if index:
            result.install(pos, options[pos][index])
            changes.append(dict(pos=pos, column=index,
                                today_before=options[pos][0].first(model.day),
                                today_after=options[pos][index].first(model.day)))
    result.value = result.objective()
    assert abs(result.value - best) < 1e-5 and result.value >= baseline - 1e-5
    receipt=dict(baseline=baseline, best=best, gain=best - baseline,
                        last_state=current, evaluations=performed, temperature=temperature,
                        search_seed=seed, accepted=accepted, downhills=downhills,
                        hard_rejections=hard_rejections, best_step=best_step,
                        seconds=time.perf_counter() - start,
                        capital_before=initial_today, capital_after=sum(costs[p][i] for p, i in best_indices.items()),
                        changes=changes)
    if deadline is not None:
        receipt['deadline_reached']=performed<evaluations
    if finalist_limit>1:
        receipt['finalist_values']=[]
        best_signature=tuple(best_indices.values())
        for signature,(value,retained) in sorted(frontier.items(),key=lambda item:item[1][0],reverse=True):
            receipt['finalist_values'].append(value)
            if signature==best_signature or candidates_out is None:continue
            candidate=clone_model(model)
            for pos,index in retained.items():
                if index:candidate.install(pos,options[pos][index])
            candidate.value=candidate.objective()
            assert abs(candidate.value-value)<1e-5 and candidate.value>baseline
            candidates_out.append(candidate)
        receipt['finalists_retained']=len(receipt['finalist_values'])
        receipt['seconds']=time.perf_counter()-start
    return result,receipt


def economic_without_today_wage(model):
    work=model.priced_work();work[model.day]=0
    return model.book.score(model.flow)-model.cost-labor_cost(work)+getattr(model,'capital_credit',lambda:0)()


class BlockMixin:
    portfolio_type=RecordingPortfolio
    block_temperatures=(0,)
    block_evaluations=200
    block_finalists=1

    def pack_block(self,obs,jobs,crew,delivery):
        required=Counter()
        for job in jobs:required.update(needs(job['ops']))
        stock=Counter(obs['private']['shed'])
        for k,n in required.items():stock[k]=max(stock[k],n)
        positions=[(4,4)]
        for _ in range(crew):positions.append(min(((4,4),(5,4),(4,5),(5,5)),key=positions.count))
        workers=[dict(pos=p,hour=2,inv={}) for p in positions]
        if obs.get('_rsi_params',{}).get('elite_network_flow'):
            from ..network_flow import route_relaxation
            receipt=route_relaxation(jobs,workers,last_hour=22 if self.day==29 else 23)
            self.metrics['flow_calls']+=1
            self.metrics['flow_seconds']+=receipt['seconds']
            self.metrics['flow_rejected']+=not receipt['feasible']
            if not receipt['feasible']:
                return {'unassigned':list(range(len(jobs))),'flow_receipt':receipt}
        return solve_routes(jobs,workers,dict(stock),last_hour=22 if self.day==29 else 23,
            track_collect=True,evaluation_budget=6000,return_to_shed=delivery,
            end_service=3 if delivery else 1,selective_return=True,
            delivery_jobs=self.delivery_set(jobs))

    @staticmethod
    def jobs_match(model,jobs):
        expected={pos:project.first(model.day)[1] for pos,project in model.projects.items()
                  if project.first(model.day)[1]}
        actual={tuple(job['pos']):tuple(tuple(op) for op in job['ops']) for job in jobs}
        return expected==actual

    def certify_candidates(self,obs,candidates,budget,baseline,best,best_gain,receipts,structural_ids=()):
        seen=set()
        for candidate in sorted(candidates,key=economic_without_today_wage,reverse=True):
            signature=tuple((pos,p.days) for pos,p in candidate.projects.items())
            if signature in seen:continue
            seen.add(signature)
            trial=copy.copy(self);trial.jobs=[]
            trial._build_jobs(obs,candidate,list(candidate.projects),budget);trial._requirements()
            if not self.jobs_match(candidate,trial.jobs):
                receipts.append(dict(gate='jobs clipped by procurement'));continue
            crews=(self.crew,max(1,self.crew-1))
            if id(candidate) in structural_ids:crews+=tuple(range(self.crew+1,min(15,self.crew+2)+1))
            for crew in dict.fromkeys(crews):
                gain=economic_without_today_wage(candidate)-fibcost(crew)-baseline
                if gain<=best_gain:continue
                result=trial.pack_block(obs,trial.jobs,crew,trial.delivery)
                receipts.append(dict(crew=crew,gain=gain,missing=len(result['unassigned'])))
                if not result['unassigned']:
                    best=(candidate,trial,crew,result);best_gain=gain
        return best,best_gain

    def guard_extra(self,obs,model,incumbent,incumbent_gain,best,best_gain,receipt):
        receipt['proposed_gain']=best_gain
        if best is not incumbent and best and obs.get('_rsi_params',{}).get('elite_response_game'):
            from ..elite_response_game import compare,prefer_candidate
            retained_model=incumbent[0] if incumbent else model
            retained_crew=incumbent[2] if incumbent else self.crew
            response=compare(obs,[retained_model,best[0]],[retained_crew,best[2]],
                             obs.get('_rsi_response_deadline',time.perf_counter()))
            # An incomplete extra comparison has not established improvement.
            # The inherited response gate keeps its original timeout behavior.
            keep=not (response.get('completed') and prefer_candidate(response))
            response['kept_incumbent']=keep;receipt['response_game']=response
            if keep:best,best_gain=incumbent,incumbent_gain
        receipt.update(selected=best is not incumbent,final_gain=best_gain)
        return best,best_gain

    def begin_day(self,obs):
        self.block_route_certificate=None
        super().begin_day(obs)
        began=time.perf_counter();model=self.economic_model
        report=dict(accepted=False,branches=[],gate=None)
        PORTFOLIO_REPORT['days'][-1]['block_search']=report
        if not self.jobs_match(model,self.jobs):
            report['gate']='baseline modeled jobs differ from committed jobs';return
        options={}
        for pos,project in model.projects.items():
            pool=model.column_pool.get(pos,{}).copy();pool[project.days]=project
            options[pos]=[project]+[p for days,p in pool.items() if days!=project.days]
        candidates=[]
        for temperature in self.block_temperatures:
            additional=[]
            candidate,receipt=search(model,options,self.block_evaluations,temperature,7,
                                     finalists=self.block_finalists,candidates_out=additional)
            report['branches'].append(receipt)
            if receipt['gain']>1:candidates.append(candidate)
            candidates.extend(extra for extra in additional if extra.value-receipt['baseline']>1)
        structural_ids=set()
        if obs.get('_rsi_params',{}).get('elite_structure'):
            from ..elite_structure import candidates as structure_candidates
            farm=obs['farms'][obs['player']]
            herd=sum(isinstance(t,dict) and 'animal' in t for row in farm['tiles'] for t in row)
            budget=self.cash_available(obs)-fibcost(8)-herd*obs['market']['prices']['WHEAT']-100
            if self.buy_land:budget-=(1000,2000,4000)[len(farm['unlocked_quadrants'])-1]
            allowance=float(obs.get('_rsi_structure_allowance',.4))
            structural,details=structure_candidates(model,obs,budget,time.perf_counter()+allowance)
            report['structure_search']=details
            candidates.extend(structural);structural_ids={id(c) for c in structural}
        extras=any(obs.get('_rsi_params',{}).get(k) for k in ('elite_anytime_search','elite_future_proposals'))
        if not candidates and not extras:
            report['gate']='no model gain';report['seconds']=time.perf_counter()-began;return
        base_pack=self.pack_block(obs,self.jobs,self.crew,self.delivery)
        if base_pack['unassigned']:
            report['gate']='baseline complete route unavailable';report['seconds']=time.perf_counter()-began;return
        farm=obs['farms'][obs['player']]
        herd=sum(isinstance(t,dict) and 'animal' in t for row in farm['tiles'] for t in row)
        budget=self.cash_available(obs)-fibcost(8)-herd*obs['market']['prices']['WHEAT']-100
        if self.buy_land:budget-=(1000,2000,4000)[len(farm['unlocked_quadrants'])-1]
        baseline=economic_without_today_wage(model)-fibcost(self.crew)
        report['certifications']=[]
        best,best_gain=self.certify_candidates(obs,candidates,budget,baseline,None,1,
                                              report['certifications'],structural_ids)
        if best and obs.get('_rsi_params',{}).get('elite_response_game'):
            from ..elite_response_game import compare,prefer_candidate
            candidate,trial,crew,result=best
            receipt=compare(obs,[model,candidate],[self.crew,crew],
                            obs.get('_rsi_response_deadline',time.perf_counter()))
            keep=not prefer_candidate(receipt)
            receipt['kept_baseline']=keep;report['response_game']=receipt
            if keep:best=None;best_gain=1
        if obs.get('_rsi_params',{}).get('elite_future_proposals'):
            from ..elite_future_search import offer_proposals
            extra_started=time.perf_counter();incumbent,incumbent_gain=best,best_gain
            proposal,receipt=offer_proposals(model,obs,obs.get('_rsi_future_proposals'))
            receipt['certifications']=[]
            if proposal is not None:
                best,best_gain=self.certify_candidates(obs,[proposal],budget,baseline,best,best_gain,
                                                      receipt['certifications'])
                best,best_gain=self.guard_extra(obs,model,incumbent,incumbent_gain,best,best_gain,receipt)
            receipt['seconds']=time.perf_counter()-extra_started
            report['future_proposals']=receipt
        if obs.get('_rsi_params',{}).get('elite_anytime_search'):
            from ..elite_anytime import improve
            # Preserve the entire inherited decision, including its response
            # gate and route certificate, before considering extra proposals.
            incumbent,incumbent_gain=best,best_gain
            extra_started=time.perf_counter()
            best,best_gain,anytime=improve(self,obs,model,options,best,best_gain,budget,baseline)
            best,best_gain=self.guard_extra(obs,model,incumbent,incumbent_gain,best,best_gain,anytime)
            anytime['seconds']=time.perf_counter()-extra_started
            report['anytime_search']=anytime
        if best:
            candidate,trial,crew,result=best
            self.economic_model=candidate;self.jobs=trial.jobs;self.crew=crew
            self.delivery=trial.delivery;self.certification_uncovered=0;self._requirements()
            report.update(accepted=True,gate='complete today route, positive integer wage gain',
                          predicted_gain=best_gain,crew=self.crew)
            if structural_ids:report['structure_selected']=id(candidate) in structural_ids
            # Execution adapters may additionally validate and carry this
            # certificate through procurement to actual dispatch.
            self.block_route_certificate=dict(day=self.day,jobs=copy.deepcopy(self.jobs),
                result=copy.deepcopy(result),crew=self.crew,start_hour=2,delivery=self.delivery)
            PORTFOLIO_REPORT['days'][-1].update(crew=self.crew,jobs=len(self.jobs),
                job_details=self.jobs,seeds=dict(self.want_seeds),animals=dict(self.want_animals),
                objective=candidate.value,modeled_work=candidate.work[self.day],
                modeled_daily_labor=labor_cost([candidate.work[self.day]]),delivery=self.delivery)
        else:report['gate']='no complete route with positive integer wage gain'
        report['seconds']=time.perf_counter()-began


class BlockPlanner(BlockMixin,AdaptivePlanner):
    pass

_players={};_beliefs={}
def agent(observation,configuration=None):
    step=int(observation['step']);p=int(observation['player'])
    if step==0:_players.pop(p,None);_beliefs[p]=InventoryBelief()
    belief=_beliefs.setdefault(p,InventoryBelief());belief.update(observation)
    obs=dict(observation);obs['_inventory_belief']=belief.snapshot()
    if step<360:action=_opening(observation,configuration)
    else:
        if p not in _players or step==360:_players[p]=BlockPlanner()
        action=_players[p].act(obs,configuration)
        if step%24==0:PORTFOLIO_REPORT['days'][-1]['inventory_belief']=belief.snapshot()
    belief.remember(observation,action)
    return action


